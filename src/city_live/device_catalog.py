"""Runtime view of the reconciled B-device catalog.

The JSON is generated by ``tools/build_device_catalog.py``; this module never
parses the source YAML and is therefore safe for the service runtime.
"""
from dataclasses import dataclass
from functools import lru_cache
import json
from pathlib import Path
from types import MappingProxyType

from .records import LiveError, numeric
from .registry import Sensor, validate_registry

CATALOG_PATH = Path(__file__).with_name("data") / "device_catalog.json"


@dataclass(frozen=True, slots=True)
class Actuator:
    device_id: str
    zone_id: str
    core_zone_id: str
    type: str
    family: str
    effect_tag: str
    target_id: str | None
    supported: bool
    physical_id: str | None
    aliases: tuple
    sensor_ids: tuple
    backup_ids: tuple
    commands: tuple


class DeviceCatalog:
    def __init__(self, payload):
        self.version = payload["version"]
        self.zones = MappingProxyType(dict(payload["zones"]))
        self.sensors = tuple(
            Sensor(
                row["sensor_id"], row["zone_id"], row["type"], row["unit"],
                row["description"], tuple(row["normal_limits"]), tuple(row["hard_limits"]),
                row["interval"], tuple(row["linked_device_ids"]), tuple(row["backup_ids"]),
                row["source"],
            )
            for row in payload["sensors"]
        )
        validate_registry(self.sensors)
        self.actuators = tuple(
            Actuator(
                row["device_id"], row["zone_id"], row["core_zone_id"], row["type"],
                row["family"], row["effect_tag"], row["target_id"], bool(row["supported"]),
                row["physical_id"], tuple(row.get("aliases", ())),
                tuple(row.get("sensor_ids", ())),
                tuple(row.get("backup_ids", ())), tuple(row.get("commands", ())),
            )
            for row in payload["actuators"]
        )
        self._sensors = MappingProxyType({row.sensor_id: row for row in self.sensors})
        self._actuators = {}
        for row in self.actuators:
            for name in (row.device_id, *row.aliases):
                if name in self._actuators:
                    raise LiveError("INVALID_REGISTRY")
                self._actuators[name] = row
        self._actuators = MappingProxyType(self._actuators)

    def sensor(self, sensor_id):
        row = self._sensors.get(sensor_id)
        if row is None:
            raise LiveError("SENSOR_NOT_FOUND")
        return row

    def actuator(self, device_id):
        row = self._actuators.get(device_id)
        if row is None:
            raise LiveError("UNSUPPORTED_DEVICE")
        return row

    def supported_sensor(self, sensor_id):
        row = self._sensors.get(sensor_id)
        return bool(row and row.source)

    def sensor_row(self, sensor_id):
        return self._sensors.get(sensor_id)

    def actuator_row(self, device_id):
        return self._actuators.get(device_id)

    def command_effect(self, device_id, requested, effective):
        row = self.actuator(device_id)
        if not row.supported or row.target_id is None:
            raise LiveError("UNSUPPORTED_DEVICE")
        actual = requested if effective is None else effective
        if row.family == "pump":
            if type(requested) is not bool or type(actual) is not bool:
                raise LiveError("INVALID_ARGUMENT")
            return ({"tag": "pump_speed", "target_id": row.target_id,
                     "speed_fraction": 1.0 if actual else 0.0}, actual)
        if row.family == "valve":
            numeric(requested, 0, 1)
            numeric(actual, 0, 1)
            return ({"tag": "valve_position", "target_id": row.target_id,
                     "opening_fraction": actual}, actual)
        if row.family == "signal":
            if requested not in ("normal", "priority", "stop") or actual not in (
                    "normal", "priority", "stop"):
                raise LiveError("UNSUPPORTED_COMMAND")
            return ({"tag": "signal_mode", "target_id": row.target_id, "mode": actual},
                    actual)
        if row.family == "feeder":
            if type(requested) is not bool or type(actual) is not bool:
                raise LiveError("INVALID_ARGUMENT")
            return ({"tag": "feeder_position", "target_id": row.target_id,
                     "closed": actual}, actual)
        raise LiveError("UNSUPPORTED_COMMAND")


@lru_cache(maxsize=1)
def load_catalog():
    payload = json.loads(CATALOG_PATH.read_text(encoding="utf-8"))
    return DeviceCatalog(payload)


def load_catalog_file(path):
    return DeviceCatalog(json.loads(Path(path).read_text(encoding="utf-8")))
