import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const file=new URL('../src/city_dashboard/web/history.js',import.meta.url);
assert.ok(await fs.stat(file).catch(()=>null),'D05 needs bounded run-aware chart history');
const {DashboardHistory,lineSegments}=await import(file);
const h=new DashboardHistory();
const rec=(seq,tick,value)=>({seq,run_id:'a',sensor_id:'DTN-WLV-01',sim_tick:tick,delivery_tick:seq,reported_value:value,unit:'cm'});
const report=(records,extra={})=>({visibility:'REPORTED_ONLY',run_id:'a',records,first_retained_seq:records[0]?.seq||1,...extra});
h.accept(report([rec(1,5,12),rec(2,10,null)]));
assert.equal(h.series.get('DTN-WLV-01').length,2);
h.accept(report([rec(1,5,12),rec(2,10,null)]));assert.equal(h.series.get('DTN-WLV-01').length,2,'polls must not duplicate samples');
h.accept(report([rec(3,2,8)]));assert.equal(h.series.get('DTN-WLV-01').at(-1).sim_tick,2,'delayed sample identity retained');
assert.equal(lineSegments([{sim_tick:1,reported_value:2},{sim_tick:2,reported_value:null},{sim_tick:3,reported_value:4}]).length,2,'null must break chart paths');
h.accept(report([rec(9,30,1)]));assert.match(h.notice,/HISTORY_GAP/);assert.equal(h.series.get('DTN-WLV-01').length,1,'resync starts at retained observations');
h.accept(report([],{run_id:'b'}));assert.equal(h.series.size,0);assert.equal(h.events.length,0);
for(let i=1;i<1400;i++)h.accept(report([rec(i,i,i)],{run_id:'a'}));
assert.ok(h.series.get('DTN-WLV-01').length<=1000);assert.ok(h.events.length<=512);
for(let i=1;i<200;i++)h.accept(report([{...rec(i,i,i),sensor_id:'replacement-'+i}],{run_id:'many'}));
assert.ok(h.series.size<=64,'replacement identities must not grow series map indefinitely');
console.log('D05 history dedup/null/delay/gap/reset/bounds passed');
